/**
 * R117's guard: a `<file>.<ext>:<line>` pointer written into a comment or a doc rots silently.
 *
 * The measured failure mode is not that somebody wrote a wrong number. It is that the number was
 * RIGHT when written and an unrelated edit moved the target, so the pointer keeps reading as
 * evidence while pointing at something else. Two of the four measured instances invalidated their
 * own pointer in the commit that wrote them — one comment pushed its own target down by exactly
 * its own length. Nothing in the repo could see that happen, so it kept happening; the previous
 * session added more citations while writing about the ones it was fixing.
 *
 * The rule: **cite greppable NAMES, never line numbers.** Every target in every measured instance
 * was uniquely greppable (a declaration name, a pushed string literal, a section heading), and the
 * repo already does this correctly in places.
 *
 * Two scope decisions, made deliberately rather than fallen into:
 *
 * 1. **Same-file citations are banned too, not only cross-file ones.** The worst measured instance
 *    was a file citing ITSELF: a twelve-line comment quoting a line number twelve lines below,
 *    which its own insertion had already pushed out from under it. Same-file pointers rot at least
 *    as easily as cross-file ones, and they are no harder to replace with a name.
 *
 * 2. **This is a test, not a lint rule.** Biome 1.9 (this repo's linter) has no custom-rule
 *    mechanism, so a lint rule would mean a second linter. A test also gets to fail on the ALLOWLIST
 *    rotting, which a lint rule could not express.
 *
 * Historical records are exempt by directory rather than by allowlist entry, because their bodies
 * must not be rewritten at all: sealed campaign pre-commitments, and dated plans and specs whose
 * whole value is being what was written on that date. A pointer inside one of those is a record of
 * a claim, not a claim being made now.
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { Glob } from "bun";

/**
 * File extensions whose `name.ext:123` form counts as a citation.
 *
 * `.al` is included even though LethAL's own mutant-site output is literally `file:line`, because
 * AL source pointers in comments rot exactly like TypeScript ones. Example output that happens to
 * contain a mutant site is handled by {@link ALLOWLIST}, where each one carries its reason.
 */
const CITED_EXTENSIONS = ["ts", "al", "md"] as const;

/** Matches a bare `basename.ext:123`, with or without a directory prefix in front of it. */
export const CITATION_PATTERN = new RegExp(
  `[A-Za-z0-9_][A-Za-z0-9_.-]*\\.(?:${CITED_EXTENSIONS.join("|")}):\\d+`,
  "g",
);

/** Globs, relative to the repo root, whose files are scanned. */
export const SCANNED_GLOBS: readonly string[] = [
  "*.md",
  "packages/*/src/**/*.ts",
  "packages/*/tests/**/*.ts",
  "packages/*/itest/**/*.ts",
  "scripts/**/*.ts",
  "docs/*.md",
  "docs/roadmap/*.md",
  "docs/measurements/*.md",
  "fixtures/**/README.md",
];

/**
 * Path prefixes skipped even when a scanned glob reaches them. Each is a RECORD whose body must
 * not be rewritten, so a pointer inside one cannot be fixed and must not be reported as fixable.
 */
