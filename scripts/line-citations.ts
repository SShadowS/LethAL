/** True when `file` sits under a prefix that is exempt by rule. */
export function isExempt(file: string): boolean {
  return EXEMPT_PREFIXES.some(({ prefix }) => file.startsWith(prefix));
}

/** Every citation in one file's text, with 1-based line numbers. */
export function findCitations(file: string, text: string): Citation[] {
  const found: Citation[] = [];
  const lines = text.split("\n");
  for (const [index, line] of lines.entries()) {
    for (const match of line.matchAll(CITATION_PATTERN)) {
      found.push({ file, line: index + 1, text: match[0] });
    }
  }
  return found;
}

/** True when this exact (file, citation text) pair is on the allowlist. */
export function isAllowlisted(citation: Citation): boolean {
  return ALLOWLIST.some(
    (entry) => entry.file === citation.file && entry.citation === citation.text,
  );
}

/** Every scanned file in the repo, repo-relative, forward-slashed, sorted. */
export function scannedFiles(root: string): string[] {
  const seen = new Set<string>();
  for (const pattern of SCANNED_GLOBS) {
    for (const hit of new Glob(pattern).scanSync({ cwd: root, onlyFiles: true })) {
      const normalized = hit.replaceAll("\\", "/");
      if (!isExempt(normalized)) seen.add(normalized);
    }
  }
  return [...seen].sort();
}

/** Every citation in the repo that is not exempt by directory. */
export function scanRepo(root: string): Citation[] {
  return scannedFiles(root).flatMap((file) =>
    findCitations(file, readFileSync(join(root, file), "utf8")),
  );
}
